def build_prompt(
    topic: str,
    platform: str,
    tone: str,
    word_count: int,
) -> str:
    """Собирает пользовательское сообщение с параметрами публикации."""

    return (
        "Создай публикацию со следующими параметрами.\n\n"
        f"ТЕМА:\n{topic}\n\n"
        f"ПЛОЩАДКА: {platform}\n"
        f"ТОНАЛЬНОСТЬ: {tone}\n"
        f"ЖЕЛАЕМЫЙ ОБЪЁМ: около {word_count} слов.\n\n"
        "Подготовь законченный текст, который можно использовать "
        "в качестве публикации без дополнительного редактирования."
    )


def build_edit_prompt(
    text: str,
    action: str,
    custom_instruction: str = "",
    tone: str | None = None,
) -> str:
    """Собирает задание для редактирования публикации."""

    action_instructions = {
        "improve": (
            "Улучши качество текста. Сделай формулировки более естественными, "
            "связными и выразительными. Устрани повторы и неудачные обороты, "
            "сохранив смысл и примерный объём."
        ),
        "proofread": (
            "Исправь орфографические, грамматические и пунктуационные ошибки. "
            "Не переписывай текст без необходимости и сохрани авторский стиль."
        ),
        "shorten": (
            "Сократи текст, убрав повторы, лишние слова и второстепенные детали. "
            "Сохрани главную мысль и важную информацию."
        ),
        "expand": (
            "Расширь текст, подробнее раскрывая исходную тему. "
            "Добавляй пояснения и развивай уже имеющиеся мысли, "
            "но не придумывай факты и не повторяй одну мысль."
        ),
        "change_tone": (
            f"Перепиши текст в следующей тональности: {tone}. "
            "Сохрани основную мысль и фактическое содержание."
        ),
        "custom": "",
    }

    if action not in action_instructions:
        raise ValueError("Неизвестный режим редактирования.")

    instruction = action_instructions[action]

    if custom_instruction:
        instruction += (
            "\n\nДОПОЛНИТЕЛЬНАЯ ИНСТРУКЦИЯ ПОЛЬЗОВАТЕЛЯ:\n"
            f"{custom_instruction}"
        )

    return (
        "Отредактируй предоставленную публикацию.\n\n"
        f"ЗАДАНИЕ:\n{instruction}\n\n"
        "ИСХОДНЫЙ ТЕКСТ:\n"
        "----- НАЧАЛО ТЕКСТА -----\n"
        f"{text}\n"
        "----- КОНЕЦ ТЕКСТА -----\n\n"
        "Верни только итоговую версию публикации."
    )
