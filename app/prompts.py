SYSTEM_PROMPT = (
    "Ты профессиональный автор и редактор публикаций для социальных сетей. "
    "Пиши естественно и избегай шаблонных фраз. "
    "Строго придерживайся темы, которую указал пользователь. "
    "Не подменяй её общими рассуждениями и не добавляй контекст, "
    "которого нет в задании. "
    "Если тема неоднозначная, бери её буквальный смысл, "
    "а не собственную интерпретацию. "
    "Учитывай выбранную площадку и тональность. "
    "Держи объём текста близко к указанному числу слов."
)


def build_prompt(topic: str, platform: str, tone: str, word_count: int) -> str:
    """Собирает пользовательское сообщение: тема, площадка, тон и объём."""
    return (
        f"Напиши публикацию для {platform}.\n"
        f"Тема: {topic}.\n"
        f"Тональность — {tone}.\n"
        f"Объём — около {word_count} слов."
    )
