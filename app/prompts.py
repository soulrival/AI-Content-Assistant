def build_variants_prompt(
    topic: str,
    platform: str,
    tone: str,
    word_count: int,
    selected_styles: list[str],
    target_audience: str = DEFAULT_TARGET_AUDIENCE,
    publication_goal: str = DEFAULT_PUBLICATION_GOAL,
    additional_wishes: str = "",
) -> str:
    """Формирует запрос на генерацию нескольких вариантов публикации."""

    minimum_words, maximum_words = _get_word_count_limits(word_count)
    additional_settings = _build_additional_settings_prompt(
        target_audience,
        publication_goal,
        additional_wishes,
    )

    style_descriptions = "\n".join(
        (
            f"- {style}: {VARIANT_STYLES[style]['label']}. "
            f"{VARIANT_STYLES[style]['description']}"
        )
        for style in selected_styles
    )

    styles_json = ", ".join(
        f'"{style}"' for style in selected_styles
    )

    return (
        "Создай несколько самостоятельных вариантов публикации "
        "на одну и ту же тему.\n\n"

        f"ТЕМА:\n{topic}\n\n"
        f"ПЛОЩАДКА: {platform}\n"
        f"ТОНАЛЬНОСТЬ: {tone}\n"
        f"{additional_settings}\n\n"
        f"ЖЕЛАЕМЫЙ ОБЪЁМ КАЖДОГО ВАРИАНТА: {word_count} слов.\n"
        f"ДОПУСТИМЫЙ ДИАПАЗОН ДЛЯ КАЖДОГО: от {minimum_words} до "
        f"{maximum_words} слов.\n\n"

        "СТИЛИ ВАРИАНТОВ:\n"
        f"{style_descriptions}\n\n"

        "ВАЖНЫЕ ТРЕБОВАНИЯ:\n"
        "1. Все варианты должны раскрывать одну и ту же тему.\n"
        "2. Все варианты должны соответствовать указанной площадке "
        "и выбранной тональности.\n"
        "3. Стили определяют способ подачи материала, а не тональность. "
        "Не меняй выбранную тональность между вариантами.\n"
        "4. Варианты должны заметно отличаться структурой, акцентами "
        "и способом раскрытия темы, а не только отдельными словами.\n"
        "5. Каждый вариант должен быть самостоятельной законченной публикацией.\n"
        "6. Не придумывай факты, статистику, исследования, цитаты и события.\n"
        "7. Не добавляй искусственные повторы ради достижения нужного объёма.\n"
        "8. Не включай в тексты название стиля или описание того, "
        "как был создан вариант.\n\n"

        "ФОРМАТ ОТВЕТА:\n"
        "Верни только корректный JSON без Markdown-разметки и пояснений. "
        "Используй следующую структуру:\n\n"
        "{\n"
        '  "variants": [\n'
        "    {\n"
        '      "style": "идентификатор стиля",\n'
        '      "text": "текст публикации"\n'
        "    }\n"
        "  ]\n"
        "}\n\n"

        "В массиве должны находиться все запрошенные варианты, "
        "по одному для каждого стиля.\n"
        f"Используй только следующие идентификаторы стилей: {styles_json}.\n"
        "Не добавляй никаких других полей."
    )


def build_edit_prompt(
    text: str,
    action: str,
    custom_instruction: str = "",
    tone: str | None = None,
) -> str:
    """Собирает задание для редактирования публикации."""

    action_instructions = {
        "improve": (
            "Улучши качество текста. Сделай формулировки более естественными, "
            "связными и выразительными. Устрани повторы и неудачные обороты, "
            "сохранив смысл и примерный объём."
        ),
        "proofread": (
            "Исправь орфографические, грамматические и пунктуационные ошибки. "
            "Не переписывай текст без необходимости и сохрани авторский стиль."
        ),
        "shorten": (
            "Сократи текст, убрав повторы, лишние слова и второстепенные детали. "
            "Сохрани главную мысль и важную информацию."
        ),
        "expand": (
            "Расширь текст, подробнее раскрывая исходную тему. "
            "Добавляй пояснения и развивай уже имеющиеся мысли, "
            "но не придумывай факты и не повторяй одну мысль."
        ),
        "change_tone": (
            f"Перепиши текст в следующей тональности: {tone}. "
            "Сохрани основную мысль и фактическое содержание."
        ),
        "custom": "",
    }

    if action not in action_instructions:
        raise ValueError("Неизвестный режим редактирования.")

    instruction = action_instructions[action]

    if custom_instruction:
        instruction += (
            "\n\nДОПОЛНИТЕЛЬНАЯ ИНСТРУКЦИЯ ПОЛЬЗОВАТЕЛЯ:\n"
            f"{custom_instruction}"
        )

    return (
        "Отредактируй предоставленную публикацию.\n\n"
        f"ЗАДАНИЕ:\n{instruction}\n\n"
        "ИСХОДНЫЙ ТЕКСТ:\n"
        "----- НАЧАЛО ТЕКСТА -----\n"
        f"{text}\n"
        "----- КОНЕЦ ТЕКСТА -----\n\n"
        "Верни только итоговую версию публикации."
    )